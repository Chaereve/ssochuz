import assert from 'node:assert/strict';
import {aliasesOf, parseAliases, matchedAlias, applyReadingGroup, readingParts, clearReadingGroup} from '../src/shared/reading-groups.js';
import {metaFromForm, newBookRecord, renameReferences, removeBookReferences} from '../src/admin/utils/books.js';
globalThis.window = {CZ: {}};
assert.deepEqual(aliasesOf({title:'Alpha'}), []);
assert.deepEqual(parseAliases('Alpha\n Bí Mật\nbi mat\nOriginal Name\n', 'Alpha'), ['Bí Mật','Original Name']);
assert.equal(matchedAlias({aliases:['Bí Mật']}, 'BI MAT'), 'Bí Mật');
assert.equal(matchedAlias({aliases:['Bí Mật']}, ''), '');
assert.throws(() => parseAliases('a'.repeat(161)), /160/);
assert.throws(() => parseAliases(Array(21).fill('a')), /20/);
const old = {slug:'a',title:'A',aliases:['Alias'],readingGroup:'g',readingOrder:1,partType:'main'};
assert.deepEqual(metaFromForm(old, {title:'A'}).aliases, ['Alias']);
assert.deepEqual(metaFromForm(old, {title:'A',aliases:''}).aliases, []);
assert.deepEqual(newBookRecord({title:'New',aliases:'Name 1\nName 2'}).meta.aliases, ['Name 1','Name 2']);
const reg = {lib:[{slug:'a', title:'A', chapters:2},{slug:'b',title:'B',chapters:1},{slug:'c',title:'C'}]};
applyReadingGroup(reg,'a',[{slug:'a',type:'main'},{slug:'b',type:'extra'},{slug:'c',type:'special'}]);
assert.deepEqual(readingParts(reg.lib,reg.lib[0]).map(n=>n.slug), ['a','b','c']);
assert.equal(reg.lib[0].chapters,2);
applyReadingGroup(reg,'a',[{slug:'b',type:'main'},{slug:'a',type:'sequel'}]);
assert.deepEqual(readingParts(reg.lib,reg.lib[0]).map(n=>n.slug), ['b','a']);
assert.equal(reg.lib[2].readingGroup,undefined);
const before = JSON.stringify(reg);
for (const parts of [[{slug:'a',type:'main'}],[{slug:'a',type:'main'},{slug:'a',type:'extra'}],[{slug:'a',type:'main'},{slug:'missing',type:'extra'}],[{slug:'a',type:'main'},{slug:'b',type:'__proto__'}]]) assert.throws(()=>applyReadingGroup(reg,'a',parts));
assert.equal(JSON.stringify(reg),before,'invalid input cannot partially mutate registry');
reg.lib[2].readingGroup = 'another';
assert.throws(()=>applyReadingGroup(reg,'a',[{slug:'a',type:'main'},{slug:'c',type:'extra'}]),/nhóm khác/);
clearReadingGroup(reg.lib[2]);
reg.lib[0].slug='renamed';renameReferences(reg,'a','renamed');
assert.deepEqual(readingParts(reg.lib,reg.lib[0]).map(n=>n.slug),['b','renamed']);
removeBookReferences(reg,'b');
assert.equal(reg.lib[0].readingGroup,undefined,'deleting a member prunes singleton');
applyReadingGroup(reg,'renamed',[{slug:'renamed',type:'main'},{slug:'c',type:'extra'}]);
applyReadingGroup(reg,'renamed',[]);
assert.ok(reg.lib.every(n=>!n.readingGroup));
console.log(JSON.stringify({errors0:[],checked:'aliases validation, legacy preservation, new book, grouping/order/types, atomic validation, rename/delete/unlink'}));
