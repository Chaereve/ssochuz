import assert from 'node:assert/strict';
import { pushAudience, pushTopics } from '../worker/push-audience.js';
assert.equal(pushTopics(undefined), null);
assert.equal(pushTopics(['a', '../b']), null);
assert.equal(pushTopics(Array(501).fill('a')), null);
assert.deepEqual(pushTopics(['b', 'a', 'a']), ['a', 'b']);
let calls = 0, failed = false, follows = ['a'];
const env = {SUPABASE_URL: 'https://test.supabase.co', SUPABASE_SERVICE_ROLE: 'test-only-key'};
const fake = async (url, opts) => {
  calls++;
  assert.equal(opts.headers.apikey, 'test-only-key');
  assert.equal(new URL(url).searchParams.get('user_id'), 'eq.user-a');
  const slug = new URL(url).searchParams.get('story_id').slice(3);
  return {ok: !failed, json: async () => follows.includes(slug) ? [{story_id: slug}] : []};
};
let allowed = pushAudience(env, fake);
const guest = {scopeVersion: 2, topics: ['a']};
assert.equal(await allowed(guest, 'a'), true);
assert.equal(await allowed(guest, 'b'), false);
assert.equal(await allowed({topics: ['a']}, 'a'), false, 'legacy fail closed');
assert.equal(calls, 0, 'guest does not need Supabase');
const account = {scopeVersion: 2, ownerId: 'user-a', topics: ['b']};
assert.equal(await allowed(account, 'a'), true, 'authoritative account follows override device snapshot');
assert.equal(await allowed(account, 'b'), false);
await allowed(account, 'a');
assert.equal(calls, 2, 'same owner/story cached within cron');
follows = [];
assert.equal(await pushAudience(env, fake)(account, 'a'), false, 'unfollow on another device respected next cron');
failed = true;
assert.equal(await pushAudience(env, fake)(account, 'a'), null, 'backend error defers without broadcasting');
assert.equal(await pushAudience({}, fake)(account, 'a'), null, 'missing secret fails closed');
assert.equal(await pushAudience(env, async () => { throw Error('offline'); })(account, 'a'), null);
console.log(JSON.stringify({errors0: [], checked: 'guest/account A/B, legacy, cross-device unfollow, unavailable backend'}));
